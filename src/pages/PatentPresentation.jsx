function renderSlide(slide) {
  switch (slide.type) {
    case "cover": return <CoverSlide />;
    case "agenda": return <AgendaSlide slide={slide} />;
    case "split": return <SplitSlide slide={slide} />;
    case "challenges": return <ChallengesSlide slide={slide} />;
    case "invention": return <InventionSlide slide={slide} />;
    case "flow": return <FlowSlide slide={slide} />;
    case "novel": return <NovelSlide slide={slide} />;
    case "tech": return <TechSlide slide={slide} />;
    case "questions": return <QuestionsSlide slide={slide} />;
    case "outcome": return <OutcomeSlide slide={slide} />;
    case "closing": return <ClosingSlide />;
    default: return null;
  }
}

export default function PatentPresentation() {
  const [current, setCurrent] = useState(0);

  const prev = () => setCurrent((c) => Math.max(0, c - 1));
  const next = () => setCurrent((c) => Math.min(slides.length - 1, c + 1));

  const handleKey = (e) => {
    if (e.key === "ArrowRight" || e.key === "ArrowDown") next();
    if (e.key === "ArrowLeft" || e.key === "ArrowUp") prev();
  };

  return (
    <div className="min-h-screen bg-gray-900 flex flex-col items-center justify-center p-4" onKeyDown={handleKey} tabIndex={0} style={{ outline: "none" }}>
      {/* Slide container — 16:9 ratio */}
      <div className="w-full max-w-5xl">
        <div className="relative w-full overflow-hidden rounded-2xl shadow-2xl" style={{ paddingBottom: "56.25%" }}>
          <div className="absolute inset-0">
            {renderSlide(slides[current])}
          </div>
        </div>

        {/* Controls */}
        <div className="flex items-center justify-between mt-5">
          <button
            onClick={prev}
            disabled={current === 0}
            className="flex items-center gap-2 px-5 py-2.5 rounded-xl text-sm font-medium transition-all disabled:opacity-30 disabled:cursor-not-allowed"
            style={{ background: current === 0 ? "#374151" : BLUE, color: "white" }}
          >
            <ChevronLeft className="w-4 h-4" /> Previous
          </button>

          {/* Dots */}
          <div className="flex items-center gap-1.5">
            {slides.map((_, i) => (
              <button
                key={i}
                onClick={() => setCurrent(i)}
                className="transition-all rounded-full"
                style={{
                  width: i === current ? "20px" : "8px",
                  height: "8px",
                  background: i === current ? BLUE : "#4b5563",
                }}
              />
            ))}
          </div>

          <button
            onClick={next}
            disabled={current === slides.length - 1}
            className="flex items-center gap-2 px-5 py-2.5 rounded-xl text-sm font-medium transition-all disabled:opacity-30 disabled:cursor-not-allowed"
            style={{ background: current === slides.length - 1 ? "#374151" : BLUE, color: "white" }}
          >
            Next <ChevronRight className="w-4 h-4" />
          </button>
        </div>

        <p className="text-center text-gray-500 text-xs mt-3">
          Slide {current + 1} of {slides.length} · Use arrow keys to navigate
        </p>
      </div>
    </div>
  );
}