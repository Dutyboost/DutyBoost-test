import { ArrowLeft } from "lucide-react";
import { Button } from "@/components/ui/button";
import { VERTICAL_LABELS, VERTICAL_FIELDS, STATUS_CLASS, carrierName, formatDate } from "@/components/admin/dutyCreditFields";

function Row({ label, value }) {
  return (
    <div className="min-w-0">
      <p className="text-xs text-muted-foreground">{label}</p>
      <p className="text-sm font-medium break-words">{value}</p>
    </div>
  );
}

export default function CompanyDutyCreditDetail({ company, tokens, onBack }) {
  return (
    <div className="space-y-4">
      <div className="flex items-center gap-3">
        <Button variant="outline" size="sm" className="gap-1.5" onClick={onBack}>
          <ArrowLeft className="w-4 h-4" /> Companies
        </Button>
        <div className="min-w-0">
          <h3 className="font-heading font-bold truncate">{company}</h3>
          <p className="text-xs text-muted-foreground">
            {tokens.length} DutyCredit{tokens.length !== 1 ? "s" : ""} generated by their customers
          </p>
        </div>
      </div>

      <div className="space-y-3">
        {tokens.map((token) => {
          const fields = VERTICAL_FIELDS[token.travel_type] || { carrier: "Company", location: "Location" };
          return (
            <div key={token.id} className="bg-card rounded-xl border border-border p-4 space-y-3">
              <div className="flex items-start justify-between gap-3">
                <div className="min-w-0">
                  <p className="font-mono text-sm font-semibold truncate">{token.token_id}</p>
                  <p className="text-xs text-muted-foreground">
                    {VERTICAL_LABELS[token.travel_type] || token.travel_type} · generated {formatDate(token.created_date)}
                  </p>
                </div>
                <span className={`text-xs px-2 py-1 rounded-full capitalize shrink-0 ${STATUS_CLASS[token.status] || ""}`}>
                  {token.status}
                </span>
              </div>

              <div className="grid grid-cols-2 gap-3">
                <Row label={fields.carrier} value={carrierName(token)} />
                <Row label={fields.location} value={token.airport || "—"} />
                {token.travel_type === "car_rental" && (
                  <Row label={fields.returnLocation} value={token.return_location || "—"} />
                )}
                <Row label="Travel date" value={formatDate(token.departure_date)} />
                {token.flight_number && <Row label="Flight number" value={token.flight_number} />}
                <Row label="Sent by" value={token.source === "partner" ? `Partner · ${token.commission_partner || token.ref_code || "—"}` : "Direct"} />
                {token.campaign_source && <Row label="Campaign" value={token.campaign_source} />}
                {token.basket_value != null && <Row label="Basket at redemption" value={`€${token.basket_value.toFixed(2)}`} />}
              </div>
            </div>
          );
        })}
      </div>
    </div>
  );
}