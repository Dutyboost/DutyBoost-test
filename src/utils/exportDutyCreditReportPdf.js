import { jsPDF } from "jspdf";

// A one-company value report: the DutyCredits that company's own travellers
// generated on DutyBoost, where they came from, and the revenue released once
// they were redeemed at a participating retailer.

const LOGO_URL = "https://media.base44.com/images/public/69c97dcd1c1950fa88424690/28ffb838a_DutyBoostLogo_1.svg";

const NAVY = [10, 31, 68];
const BODY = [51, 65, 85];
const MUTED = [100, 116, 139];
const LINE = [226, 232, 240];
const BLUE = [31, 105, 255];
const PANEL = [245, 247, 250];

const M = 16; // page margin (mm)
const PAGE_W = 210;
const PAGE_H = 297;
const CW = PAGE_W - M * 2;

// jsPDF's built-in fonts are single-byte, so typographic characters are normalised.
const clean = (value) =>
  String(value ?? "")
    .replace(/[\u2018\u2019]/g, "'")
    .replace(/[\u201C\u201D]/g, '"')
    .replace(/[\u2013\u2014]/g, "-")
    .replace(/\u00A0/g, " ")
    .replace(/\u2026/g, "...");

const money = (value) =>
  `\u20AC ${Number(value || 0).toLocaleString("en-GB", {
    minimumFractionDigits: 2,
    maximumFractionDigits: 2,
  })}`;

const shortDate = (value) =>
  value
    ? new Date(value).toLocaleDateString("en-GB", { day: "2-digit", month: "short", year: "numeric" })
    : "-";

const slug = (value) =>
  clean(value)
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "") || "partner";

async function loadLogo() {
  try {
    const res = await fetch(LOGO_URL);
    const svg = await res.text();
    const url = URL.createObjectURL(new Blob([svg], { type: "image/svg+xml" }));
    const img = await new Promise((resolve, reject) => {
      const image = new Image();
      image.onload = () => resolve(image);
      image.onerror = reject;
      image.src = url;
    });
    const w = img.naturalWidth || img.width || 1000;
    const h = img.naturalHeight || img.height || 300;
    const cw = 1600;
    const ch = Math.round(cw * (h / w));
    const canvas = document.createElement("canvas");
    canvas.width = cw;
    canvas.height = ch;
    canvas.getContext("2d").drawImage(img, 0, 0, cw, ch);
    URL.revokeObjectURL(url);
    return { dataUrl: canvas.toDataURL("image/png"), aspect: w / h };
  } catch {
    return null;
  }
}

export async function downloadCompanyDutyCreditReport({ company, tokens, verticalLabel }) {
  const doc = new jsPDF({ unit: "mm", format: "a4" });
  const logo = await loadLogo();

  const list = [...(tokens || [])].sort(
    (a, b) => new Date(b.created_date) - new Date(a.created_date)
  );

  const total = list.length;
  const active = list.filter((t) => t.status === "active").length;
  const redeemed = list.filter((t) => t.status === "redeemed").length;
  const revenue = list.reduce(
    (sum, t) => sum + (t.status === "redeemed" ? Number(t.basket_value || 0) : 0),
    0
  );

  const byLocation = new Map();
  list.forEach((token) => {
    const name = token.airport || "Not specified";
    const entry = byLocation.get(name) || { name, credits: 0, redeemed: 0 };
    entry.credits += 1;
    if (token.status === "redeemed") entry.redeemed += 1;
    byLocation.set(name, entry);
  });
  const locations = [...byLocation.values()].sort((a, b) => b.credits - a.credits);

  const dates = list.map((t) => t.created_date).filter(Boolean).sort();
  const firstDate = dates[0];
  const lastDate = dates[dates.length - 1];

  let y = M;

  // ── header ──────────────────────────────────────────────────────────────
  if (logo) {
    const height = 34 / logo.aspect;
    doc.addImage(logo.dataUrl, "PNG", M, y, 34, height);
    y += height + 6;
  } else {
    doc.setFont("helvetica", "bold");
    doc.setFontSize(16);
    doc.setTextColor(...NAVY);
    doc.text("DutyBoost", M, y + 6);
    y += 14;
  }

  doc.setDrawColor(...BLUE);
  doc.setLineWidth(0.8);
  doc.line(M, y, M + CW, y);
  y += 8;

  doc.setFont("helvetica", "bold");
  doc.setFontSize(7);
  doc.setTextColor(...BLUE);
  doc.text("PARTNER VALUE REPORT", M, y);
  y += 6;

  doc.setFontSize(19);
  doc.setTextColor(...NAVY);
  doc.text(doc.splitTextToSize(clean(company), CW)[0], M, y);
  y += 7;

  doc.setFont("helvetica", "normal");
  doc.setFontSize(9);
  doc.setTextColor(...BODY);
  doc.text(
    doc.splitTextToSize(
      clean(`${verticalLabel} - DutyCredits generated by their own travellers on DutyBoost`),
      CW
    )[0],
    M,
    y
  );
  y += 9;

  const intro =
    total > 0
      ? `Between ${shortDate(firstDate)} and ${shortDate(lastDate)}, travellers with ${company} generated ${total} DutyCredit${total === 1 ? "" : "s"} on the DutyBoost platform. ${redeemed} of them ${redeemed === 1 ? "was" : "were"} redeemed at a participating retailer, releasing ${money(revenue)} of tracked basket value.`
      : `No DutyCredits generated by ${company} travellers have been recorded yet.`;
  doc.setFontSize(10);
  doc.setTextColor(...BODY);
  const introLines = doc.splitTextToSize(clean(intro), CW);
  doc.text(introLines, M, y);
  y += introLines.length * 5 + 6;

  // ── KPI row ─────────────────────────────────────────────────────────────
  const kpis = [
    { label: "DutyCredits generated", value: String(total) },
    { label: "Active", value: String(active) },
    { label: "Redeemed", value: String(redeemed) },
    { label: "Revenue generated", value: money(revenue) },
  ];
  const gap = 4;
  const boxW = (CW - gap * (kpis.length - 1)) / kpis.length;
  kpis.forEach((kpi, index) => {
    const x = M + index * (boxW + gap);
    doc.setFillColor(...PANEL);
    doc.roundedRect(x, y, boxW, 20, 2, 2, "F");
    doc.setFont("helvetica", "bold");
    doc.setFontSize(6.5);
    doc.setTextColor(...MUTED);
    doc.text(doc.splitTextToSize(kpi.label.toUpperCase(), boxW - 8)[0], x + 4, y + 6);
    doc.setFontSize(12);
    doc.setTextColor(...NAVY);
    doc.text(kpi.value, x + 4, y + 14);
  });
  y += 27;

  // ── table helpers ───────────────────────────────────────────────────────
  const ensure = (space) => {
    if (y + space <= PAGE_H - M - 12) return;
    doc.addPage();
    y = M;
  };

  const sectionTitle = (text) => {
    ensure(16);
    doc.setFont("helvetica", "bold");
    doc.setFontSize(10);
    doc.setTextColor(...NAVY);
    doc.text(clean(text), M, y);
    y += 6;
  };

  const tableHead = (cols) => {
    ensure(14);
    doc.setFillColor(...PANEL);
    doc.rect(M, y, CW, 8, "F");
    doc.setFont("helvetica", "bold");
    doc.setFontSize(7);
    doc.setTextColor(...MUTED);
    let x = M + 3;
    cols.forEach((col) => {
      if (col.align === "right") doc.text(col.label.toUpperCase(), x + col.w - 6, y + 5.2, { align: "right" });
      else doc.text(col.label.toUpperCase(), x, y + 5.2);
      x += col.w;
    });
    y += 8;
  };

  const tableRow = (cells, cols, opts = {}) => {
    ensure(10);
    doc.setFont("helvetica", opts.bold ? "bold" : "normal");
    doc.setFontSize(8.5);
    doc.setTextColor(...(opts.bold ? NAVY : BODY));
    let x = M + 3;
    cols.forEach((col, index) => {
      const raw = clean(cells[index] ?? "-");
      let text = raw;
      if (doc.getTextWidth(text) > col.w - 8) {
        while (text.length > 1 && doc.getTextWidth(`${text}...`) > col.w - 8) text = text.slice(0, -1);
        text = `${text}...`;
      }
      if (col.align === "right") doc.text(text, x + col.w - 6, y + 5, { align: "right" });
      else doc.text(text, x, y + 5);
      x += col.w;
    });
    doc.setDrawColor(...LINE);
    doc.setLineWidth(0.2);
    doc.line(M, y + 7.5, M + CW, y + 7.5);
    y += 8.5;
  };

  // ── where the credits came from ─────────────────────────────────────────
  if (locations.length) {
    sectionTitle("Where their travellers generated their DutyCredits");
    const locationCols = [
      { label: "Location", w: 108, align: "left" },
      { label: "DutyCredits", w: 35, align: "right" },
      { label: "Redeemed", w: 35, align: "right" },
    ];
    tableHead(locationCols);
    locations.slice(0, 40).forEach((location) => {
      tableRow([location.name, String(location.credits), String(location.redeemed)], locationCols);
    });
    if (locations.length > 40) {
      doc.setFont("helvetica", "italic");
      doc.setFontSize(7.5);
      doc.setTextColor(...MUTED);
      ensure(8);
      doc.text(`Plus ${locations.length - 40} further locations.`, M, y + 4);
      y += 8;
    }
    y += 8;
  }

  // ── credit detail ───────────────────────────────────────────────────────
  if (list.length) {
    sectionTitle("DutyCredit detail");
    const detailCols = [
      { label: "Token", w: 34, align: "left" },
      { label: "Location", w: 56, align: "left" },
      { label: "Travel date", w: 26, align: "left" },
      { label: "Status", w: 24, align: "left" },
      { label: "Basket value", w: 38, align: "right" },
    ];
    tableHead(detailCols);
    const shown = list.slice(0, 120);
    shown.forEach((token) => {
      tableRow(
        [
          token.token_id,
          token.airport || "Not specified",
          shortDate(token.departure_date),
          token.status,
          token.status === "redeemed" && token.basket_value != null ? money(token.basket_value) : "-",
        ],
        detailCols
      );
    });
    if (list.length > shown.length) {
      ensure(10);
      doc.setFont("helvetica", "italic");
      doc.setFontSize(7.5);
      doc.setTextColor(...MUTED);
      doc.text(`Showing the ${shown.length} most recent of ${list.length} DutyCredits.`, M, y + 4);
      y += 8;
    }
    y += 8;
  }

  // ── closing note ────────────────────────────────────────────────────────
  ensure(34);
  doc.setFillColor(...PANEL);
  doc.roundedRect(M, y, CW, 26, 2, 2, "F");
  doc.setFont("helvetica", "bold");
  doc.setFontSize(8);
  doc.setTextColor(...NAVY);
  doc.text("How to read this report", M + 5, y + 6.5);
  doc.setFont("helvetica", "normal");
  doc.setFontSize(7.5);
  doc.setTextColor(...BODY);
  const note = doc.splitTextToSize(
    clean(
      "Revenue is recognised only when a traveller redeems a DutyCredit at a participating retailer, so the figure grows as more of the credits are used. Active credits are still valid and redeemable, and represent the upside still available to both sides."
    ),
    CW - 10
  );
  doc.text(note, M + 5, y + 11.5);
  y += 30;

  // ── footers ─────────────────────────────────────────────────────────────
  const pages = doc.getNumberOfPages();
  for (let page = 1; page <= pages; page += 1) {
    doc.setPage(page);
    doc.setDrawColor(...LINE);
    doc.setLineWidth(0.2);
    doc.line(M, PAGE_H - 14, M + CW, PAGE_H - 14);
    doc.setFont("helvetica", "normal");
    doc.setFontSize(7.5);
    doc.setTextColor(...MUTED);
    doc.text("DutyBoost - travel retail conversion layer", M, PAGE_H - 9);
    doc.text(`Page ${page} of ${pages}`, M + CW, PAGE_H - 9, { align: "right" });
  }

  doc.save(`${slug(company)}-dutycredit-report.pdf`);
}