// A terminal with no published figures still gets its own indicative numbers,
// derived from the market's total traffic: the market's calls are shared out
// across its terminals and adjusted per port, so no two ports read the same.
const stableHash = (str) => {
  let h = 2166136261;
  for (let i = 0; i < str.length; i += 1) {
    h ^= str.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return Math.abs(h);
};

const spread = (seed, min, max) => min + ((seed % 1000) / 1000) * (max - min);

// Figures for one terminal: the listed values when we have them, otherwise a
// derived estimate. Returns null when no port has been picked yet.
export function terminalTrafficFor(country, port) {
  const name = (port || "").trim();
  if (!name) return null;
  const key = (country || "").trim();
  const listed = TERMINAL_TRAFFIC[`${key}|${name}`] || TERMINAL_TRAFFIC[name];
  if (listed) return { passengersPerCall: listed[0], callsPerYear: listed[1] };

  const base = trafficDefaultsFor(key);
  if (!base) return null;
  const siblings = Math.max(1, terminalsForCountry(key).length);
  const seed = stableHash(`${key}|${name}`);
  return {
    passengersPerCall: Math.round((base.passengersPerCall * spread(seed, 0.5, 1.25)) / 10) * 10,
    callsPerYear: Math.max(20, Math.round((base.callsPerYear / siblings) * spread(seed + 7, 0.35, 1.75))),
  };
}