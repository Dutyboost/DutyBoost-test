"6. CORE BUSINESS LOGIC",
"================================================================================",
"",
"A. DutyCredit Calculation (flights)",
"------------------------------------",
"  Config:",
"    Short-haul base:  EUR 2.50 per traveler",
"    Long-haul base:   EUR 7.00 per traveler",
"    Floor:            EUR 5.00",
"    Cap:              EUR 60.00",
"",
"  Multipliers (based on total ticket price):",
"    < EUR 200:   1.0x",
"    EUR 200-499: 1.5x",
"    EUR 500-999: 2.0x",
"    >= EUR 1000: 2.5x",
"",
"  Formula:",
"    raw = basePerTraveler * numTravelers * multiplier",
"    creditAmount = clamp(raw, floor=5, cap=60)",
"",
"  Expiration:",
"    expirationDate = travelDate + 30 days",
"",
"  Voucher code format: 'DB-' + 8 random alphanumeric chars (e.g. DB-A3X7KQ2P)",
"",
"B. Redemption Tiers (applied at POS for standard vouchers)",
"----------------------------------------------------------",
"  EUR 70  - 99  -> Boarding DutyCredit:  EUR 10 discount",
"  EUR 100 - 199 -> Priority DutyCredit:  EUR 30 discount",
"  EUR 200 - 299 -> Lounge DutyCredit:    EUR 45 discount",
"  >= EUR 300    -> VIP DutyCredit:       EUR 60 discount",
"  < EUR 70      -> Not eligible (minimum spend)",
"",
"  Financial split per transaction:",
"    Platform revenue (DutyBoost fee): 2.5% of gross transaction value, capped at EUR 25.00",
"    Agency commission:                 20% of DutyBoost fee (capped at EUR 5.00 when fee is capped)",
"    Retailer pays:                     discountAmount to traveler",
"",
"C. Voucher Lifecycle",
"--------------------",
"  active -> redeemed  (after successful POS scan)",
"  active -> expired   (if expiration_date < today when scanned)",
"  Manual: admin can force-expire a voucher",
"",
"D. Invoice Generation (monthly)",
"-------------------------------",
"  Run on the 1st of each month via cron.",
"  For each retailer: sum all transactions from prior month.",
"  Create MonthlyInvoice record with amount = total platform_revenue.",
"  Note: platform_revenue = 2.5% of transaction_value, capped at EUR 25.00 per transaction.",
"  due_date = invoice_date + 14 days. Send invoice email to retailer.",
"",
"E. Agency Payouts (monthly)",
"---------------------------",
"  Run on the 1st of each month via cron.",
"  For each agency: sum all agency_commission from prior month's transactions.",
"  Note: agency_commission = 20% of platform_revenue per transaction (capped at EUR 5.00/tx).",
"  Process payout via Mollie API (bank transfer to agency IBAN).",
"",
"F. Flight Reminders",
"-------------------",
"  Run daily via cron.",
"  Find bookings where travel_date = tomorrow AND flight_reminder_disabled = false.",
"  Send reminder email to traveler_email with their voucher code + QR.",
"",

"H. Cruise Credit Logic",
"----------------------",
"  CruiseCredit generated at booking time by cruise line partner.",
"  token_id = unique credit identifier sent to traveler.",
"  Redeemable at participating port/duty-free retailers.",
"  Balance is partial-use (remaining_balance decreases per transaction).",
"",
"I. Train Credit Logic",
"---------------------",
"  TrainCredit generated at booking time by train/rail operator.",
"  Redeemable at participating station retailers before boarding.",
"  Same partial-balance model as CruiseCredit.",
"",
